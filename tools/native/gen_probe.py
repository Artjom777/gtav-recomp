"""Generate gtav/src/native/d3d_probe_list.inc: one GTAV_PROBE(addr, index) per guest
function in the D3D runtime region, skipping functions hooked elsewhere.

usage: python3 gen_probe.py ASM.json.gz OUT.inc [LO HI]
"""
import pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from genasm import load

HOOKED_ELSEWHERE = pathlib.Path(__file__).parents[2] / 'gtav' / 'src'


def hooked():
    out = set()
    for p in HOOKED_ELSEWHERE.rglob('*.cpp'):
        if p.name == 'd3d_probe.cpp':
            continue
        out |= {int(m, 16) for m in re.findall(r'(?:REX_HOOK_RAW\(sub_|GTAV_COUNT_HOOK\()([0-9A-F]{8})', p.read_text())}
    return out


def main():
    funcs = load(sys.argv[1])
    lo, hi = (int(x, 16) for x in sys.argv[3:5]) if len(sys.argv) > 4 else (0x837F0000, 0x83840000)
    skip = hooked()
    sel = [a for a in sorted(funcs) if lo <= a < hi and a not in skip]
    with open(sys.argv[2], 'w') as f:
        f.write(f'// generated by tools/native/gen_probe.py ({len(sel)} functions, {lo:08X}-{hi:08X})\n')
        for i, a in enumerate(sel):
            f.write(f'GTAV_PROBE({a:08X}, {i})\n')
        f.write(f'#define GTAV_PROBE_COUNT {len(sel)}\n')
    print(len(sel), 'probes;', len(skip), 'skipped as hooked elsewhere')


if __name__ == '__main__':
    main()
